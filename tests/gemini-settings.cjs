const {app,BrowserWindow,ipcMain}=require('electron');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const output=path.join(__dirname,'.runtime/gemini-integration');
fs.mkdirSync(output,{recursive:true});
app.setPath('userData',path.join(output,'profile'));
app.disableHardwareAcceleration();
let key=process.env.OWLIO_TEST_GEMINI_KEY;
delete process.env.OWLIO_TEST_GEMINI_KEY;
const {Store}=require('../dist/main/store');
const store=new Store(app.getPath('userData'));
const waitFor=async check=>{const end=Date.now()+8000;while(Date.now()<end){if(await check())return;await new Promise(resolve=>setTimeout(resolve,30));}throw new Error('Settings did not settle');};
app.whenReady().then(async()=>{
  key=key||store.getSettings().geminiApiKey;
  assert.ok(key,'Test API key missing');
  ipcMain.handle('get-settings',()=>store.getSettings());
  ipcMain.handle('update-settings',(_event,settings)=>store.updateSettings(settings));
  ipcMain.handle('get-last-failure',()=>null);
  ipcMain.handle('get-writing-memory',()=>({preferences:store.getWritingPreferences(),vocabulary:store.getLearnedVocabulary()}));
  for(const name of ['get-history','get-dictionary','get-snippets','get-meetings'])ipcMain.handle(name,()=>[]);
  ipcMain.handle('get-scratchpad',()=>'');
  ipcMain.handle('cancel-shortcut',()=>{});
  ipcMain.handle('get-local-models',()=>({speech:{online:true,loaded_model:'bodhan-flex',models:[{id:'bodhan-flex',name:'Bodhan Flex',downloaded:true}],jobs:[]},formatting:{online:false},pulls:[]}));
  store.updateSettings({provider:'local',localSttModel:'bodhan-flex',dictationLanguage:'hinglish',geminiApiKey:key,formattingProvider:'gemini',geminiStructuredFormatting:true});
  const window=new BrowserWindow({show:false,width:1120,height:800,webPreferences:{preload:path.join(root,'dist/preload/preload.js'),contextIsolation:true,offscreen:true,backgroundThrottling:false}});
  window.webContents.session.setPermissionRequestHandler((_contents,_permission,callback)=>callback(false));
  await window.loadFile(path.join(root,'dist/renderer/index.html'),{query:{view:'dashboard',tab:'text'}});
  const js=code=>window.webContents.executeJavaScript(code);
  await waitFor(()=>js('document.querySelector("#formatting-provider")?.value === "gemini"'));
  assert.equal(await js('document.querySelector("#gemini-api-key").type'),'password');
  assert.equal(await js('!!document.querySelector("#gemini-structured-formatting")'),false);
  await js('document.querySelector(".settings-page .header-row button").click();void 0;');
  await waitFor(()=>js('document.querySelector(".settings-page .header-row button")?.textContent.includes("Saved")'));
  await js('document.querySelector(".style-link").click();void 0;');
  await waitFor(()=>js('!!document.querySelector("#gemini-structured-formatting")'));
  assert.equal(await js('!!document.querySelector("#gemini-api-key")'),false);
  assert.equal(await js('document.querySelector("#gemini-structured-formatting").disabled'),false);
  assert.equal(await js('document.querySelector("#gemini-structured-formatting").checked'),true);
  await js('document.querySelector("#gemini-structured-formatting").click();void 0;');
  await js('document.querySelector(".style-page .header-row button").click();void 0;');
  await waitFor(()=>new Store(app.getPath('userData')).getSettings().geminiStructuredFormatting===false);
  const reloaded=new Store(app.getPath('userData')).getSettings();
  assert.equal(reloaded.formattingProvider,'gemini');
  assert.equal(reloaded.provider,'local');
  assert.equal(reloaded.localSttModel,'bodhan-flex');
  assert.equal(reloaded.geminiApiKey,key);
  assert.equal(reloaded.geminiStructuredFormatting,false);
  await js('document.querySelector("#gemini-structured-formatting").click();document.querySelector(".style-page .header-row button").click();void 0;');
  await waitFor(()=>new Store(app.getPath('userData')).getSettings().geminiStructuredFormatting===true);
  const saved=fs.readFileSync(path.join(app.getPath('userData'),'owlio_config.json'),'utf8');
  assert.ok(!saved.includes(key));
  assert.ok(JSON.parse(saved).settings.geminiApiKey.startsWith('encrypted:'));
  await js('document.querySelector(".style-page").scrollIntoView({block:"start"});void 0;');
  await new Promise(resolve=>setTimeout(resolve,200));
  fs.writeFileSync(path.join(output,'settings.png'),(await window.webContents.capturePage()).toPNG());
  fs.writeFileSync(path.join(output,'settings-result.json'),JSON.stringify({success:true,isolatedProfile:true,keyEncrypted:true,structureTogglePersists:true,speechProvider:'local',speechModel:'bodhan-flex',formattingProvider:'gemini'}));
  window.destroy();app.quit();
}).catch(error=>{console.error('Settings integration failed:',error.message);app.exit(1);});
